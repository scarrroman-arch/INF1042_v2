# Question 3 : calculs avec des nombres à virgule

valeur1 = float(input("Entrez un premier nombre à virgule : "))
valeur2 = float(input("Entrez un deuxième nombre à virgule : "))

produit = valeur1 * valeur2
difference = valeur1 - valeur2

print(f"Produit : {produit:.2f}")
print(f"Différence : {difference:.2f}")
