# Question 1 : heures, minutes et secondes dans une année

jours = 365

heures = jours * 24       # 1 jour = 24 heures
minutes = heures * 60     # 1 heure = 60 minutes
secondes = minutes * 60   # 1 minute = 60 secondes

print("Dans une année de 365 jours :")
print(f"Jours : {jours}")
print(f"Heures : {heures}")
print(f"Minutes : {minutes}")
print(f"Secondes : {secondes}")
